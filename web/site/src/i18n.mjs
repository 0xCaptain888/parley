export function english(text) {
  if (dictionary.has(text)) return dictionary.get(text);
  for (const [pattern, format] of [
    [/^(\d+) 小时后过期$/, m => `Expires in ${m[1]} h`],
    [/^(\d+) 分钟后过期$/, m => `Expires in ${m[1]} min`],
    [/^已领 (\d+) \/ (\d+) 份$/, m => `Claimed ${m[1]} / ${m[2]}`],
    [/^Parley 红包 #(\d+)$/, m => `Parley Gift #${m[1]}`],
    [/^报价 #(\d+)$/, m => `Offer #${m[1]}`],
    [/^链 (\d+) · 只读$/, m => `Chain ${m[1]} · Read only`],
    [/^(.+) \/ (.+) 位成员在开通后有另一笔操作。$/, m => `${m[1]} / ${m[2]} members acted in another transaction after opening.`],
    [/^截至区块 (\d+) · 更新于 (.+)$/, m => `Through block ${m[1]} · Updated ${m[2]}`],
    [/^更新于 (.+)$/, m => `Updated ${m[1]}`],
    [/^合约：(0x[a-fA-F0-9]+)$/, m => `Contract: ${m[1]}`],
    [/^常驻体验 Agent：(.+)\.ai，由项目方运营。$/, m => `Resident agent: ${m[1]}.ai, operated by the project.`],
    [/^体验对手方 (.+)\.ai 由项目方运营，并从统计中剔除。$/, m => `Counterparty ${m[1]}.ai is project-operated and excluded from metrics.`],
  ]) {
    const match = pattern.exec(text);
    if (match) return format(match);
  }
  return text;
}
export function localizeDom(root) {
  const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walk.nextNode(); node; node = walk.nextNode()) {
    if (node.parentElement.closest('[data-untrusted],script,style,pre')) continue;
    const trimmed = node.textContent.trim();
    if (trimmed) node.textContent = node.textContent.replace(trimmed, english(trimmed));
  }
  for (const element of root.querySelectorAll('[title],[aria-label]')) {
    for (const key of ['title', 'aria-label']) if (element.hasAttribute(key))
      element.setAttribute(key, english(element.getAttribute(key)));
  }
}
